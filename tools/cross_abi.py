#!/usr/bin/env python3
"""Compile-only ARM64 layout checks. No target executable is ever run.

The default probe measures this repository's C types, not the Linux/Asahi UAPI
or a Darwin SDK. LLVM IR constants give target sizeof/alignof/offsetof results
without QEMU or a target host. Also emits actual Mach-O/ELF object files.
"""
from __future__ import annotations
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
from typing import Any
try:
    from .lab import ROOT, read_json, regular_file
    from .uapi_contract import ident, compare_layouts
    from .source_inventory import SourceError
except ImportError:
    from lab import ROOT, read_json, regular_file
    from uapi_contract import ident, compare_layouts
    from source_inventory import SourceError

PROFILES = {
    'darwin-arm64': 'arm64-apple-macos11',
    'linux-aarch64': 'aarch64-unknown-linux-gnu',
}
MAX_IR_BYTES = 8 * 1024 * 1024


def schema(spec: dict[str, Any]) -> tuple[str, list[tuple[str, str, str]]]:
    if not isinstance(spec, dict):
        raise SourceError('Expected probe object')
    header=spec.get('header'); tag=spec.get('abi_tag')
    if not isinstance(header, str) or not re.fullmatch(r'[A-Za-z0-9_./-]+', header) or any(
            p in {'', '.', '..'} for p in header.split('/')):
        raise SourceError('Invalid include path')
    if not isinstance(tag, str) or not re.fullmatch(r'[A-Za-z0-9_.:-]{1,80}', tag):
        raise SourceError('Invalid ABI label')
    types=spec.get('types'); constants=spec.get('constants', [])
    if not isinstance(types, list) or not 1 <= len(types) <= 128:
        raise SourceError('Expected 1..128 types')
    if not isinstance(constants, list) or len(constants)>256:
        raise SourceError('Invalid constant list')
    metrics=[]; names=set()
    for item in types:
        if not isinstance(item, dict): raise SourceError('Invalid type entry')
        name=ident(item.get('name')); ctype=item.get('c_type', name)
        if name in names: raise SourceError('Duplicate type name')
        names.add(name)
        if not isinstance(ctype,str) or not re.fullmatch(r'(?:(?:struct|union) )?[A-Za-z_][A-Za-z_0-9]*',ctype):
            raise SourceError('Invalid C type')
        fields=item.get('fields', [])
        if not isinstance(fields,list) or len(fields)>256:
            raise SourceError('Invalid fields')
        validated=[ident(f) for f in fields]
        if len(set(validated))!=len(validated): raise SourceError('Duplicate field')
        metrics += [(name,'size',f'sizeof({ctype})'), (name,'align',f'_Alignof({ctype})')]
        metrics += [(name,f'field:{f}',f'offsetof({ctype}, {f})') for f in validated]
    seen=set()
    for item in constants:
        name=ident(item)
        if name in seen: raise SourceError('Duplicate constant')
        seen.add(name); metrics.append(('',name,name))
    return header, metrics


def generate(spec: dict[str, Any]) -> str:
    header, metrics=schema(spec)
    expressions=',\n'.join('  (unsigned long long)('+e+')' for _,_,e in metrics)
    return ('/* Generated by darwin-lab; compile only, no entry point. */\n'
            '#include <stddef.h>\n'+f'#include "{header}"\n'
            '_Static_assert(sizeof(unsigned long long) == 8, "64-bit metric required");\n'
            'const unsigned long long dl_abi_values[] = {\n'+expressions+'\n};\n')


def parse_ir(text: str, spec: dict[str, Any]) -> dict[str, Any]:
    _, metrics=schema(spec)
    if not isinstance(text,str) or len(text)>MAX_IR_BYTES: raise SourceError('IR exceeds limit')
    triple=re.findall(r'^target triple = "([^"\r\n]+)"$',text,re.M)
    datalayout=re.findall(r'^target datalayout = "([^"\r\n]+)"$',text,re.M)
    if len(triple)!=1 or len(datalayout)!=1: raise SourceError('Missing or duplicate target metadata')
    # Only the precise compiler-emitted data global is accepted, never functions,
    # aliases, symbol references, arbitrary expressions or copied printf output.
    matches=list(re.finditer(r'^@dl_abi_values = [^\n]*?constant \[(\d+) x i64\] \[([^\]]*)\]',text,re.M))
    definitions=re.findall(r'^@dl_abi_values\s*=',text,re.M)
    if len(matches)!=1 or len(definitions)!=1: raise SourceError('Missing or duplicate constant array')
    count=int(matches[0].group(1))
    if count!=len(metrics): raise SourceError('Metric count mismatch')
    values=[]
    for token in matches[0].group(2).split(','):
        m=re.fullmatch(r'\s*i64 (-?\d+)\s*',token)
        if not m: raise SourceError('Nonliteral constant in probe')
        n=int(m.group(1))
        if not -(1<<63)<=n<(1<<64): raise SourceError('Out-of-range constant')
        values.append(n % (1<<64))
    if len(values)!=count: raise SourceError('Initializer length mismatch')
    structs={}; constants={}
    for (name,key,_),value in zip(metrics,values):
        if not name: constants[key]=value; continue
        out=structs.setdefault(name,{'size':0,'align':0,'offsets':{}})
        if key.startswith('field:'): out['offsets'][key[6:]]=value
        else: out[key]=value
    report={'schema_version':1,'abi_tag':spec['abi_tag'],'structs':structs,
            'constants':constants,'target_triple':triple[0],'target_datalayout':datalayout[0],
            'extraction':'LLVM_IR_LITERAL_CONSTANTS','target_code_executed':False}
    compare_layouts(report,report)  # reject malformed sizes/alignments/offsets
    return report


def object_identity(data: bytes, profile: str) -> dict[str, Any]:
    """Check object header identity only. Not a linker, boot validator or loader."""
    if profile=='darwin-arm64':
        if len(data)<32: raise SourceError('Truncated Mach-O header')
        magic,cpu,subtype,kind,ncmds,command_bytes,flags,reserved=struct.unpack_from('<8I',data)
        if (magic,cpu,kind)!=(0xfeedfacf,0x0100000c,1):
            raise SourceError('Expected ARM64 Mach-O relocatable object, not a kernel')
        if command_bytes>len(data)-32 or ncmds>command_bytes//8:
            raise SourceError('Out-of-bounds Mach-O command area')
        return {'format':'MACH_O_64','architecture':'ARM64','file_kind':'RELOCATABLE_OBJECT',
                'cpu_subtype':subtype,'kernel_image':False}
    if profile=='linux-aarch64':
        if len(data)<64 or data[:7]!=b'\x7fELF\x02\x01\x01':
            raise SourceError('Expected little-endian ELF64 object')
        kind,machine=struct.unpack_from('<HH',data,16)
        if (kind,machine)!=(1,183): raise SourceError('Expected AArch64 ELF relocatable object')
        return {'format':'ELF64','architecture':'AARCH64','file_kind':'RELOCATABLE_OBJECT','kernel_image':False}
    raise SourceError('Unknown target profile')


def run_command(args: list[str], commands: list[dict[str, Any]]) -> str:
    proc=subprocess.run(args,cwd=ROOT,check=False,text=True,capture_output=True,timeout=60)
    commands.append({'command':args,'returncode':proc.returncode,'stdout':proc.stdout,'stderr':proc.stderr})
    if proc.returncode: raise SourceError('Compilation/probe command failed: '+proc.stderr[-3000:])
    return proc.stdout


def perform(clang: str, spec: dict[str, Any], build: Path) -> dict[str, Any]:
    build=build.resolve(); build.mkdir(parents=True,exist_ok=True)
    commands=[]
    version=run_command([clang,'--version'],commands)
    resource=Path(run_command([clang,'-print-resource-dir'],commands).strip())/'include'
    if not resource.is_dir(): raise SourceError('Missing compiler builtin headers')
    generated=build/'layout_probe.c'; generated.write_text(generate(spec),encoding='utf-8')
    profiles={}
    files=['contracts/buffer_lifetime.h','contracts/buffer_lifetime.c','core/backing_store.h','core/backing_store.c','core/mapping_ticket.h','core/mapping_ticket.c','probe/memory_probe.c','probe/memory_probe.h','probe/memory_probe_protocol.h']
    for profile,triple in PROFILES.items():
        flags=[clang,'--target='+triple,'-std=c11','-ffreestanding','-nostdinc','-isystem',str(resource),
               '-Wall','-Wextra','-Wpedantic','-Werror','-Wframe-larger-than=1024','-Icontracts','-Icore','-Iprobe']
        ir=build/(profile+'.ll')
        run_command([*flags,'-S','-emit-llvm',str(generated),'-o',str(ir)],commands)
        parsed=parse_ir(ir.read_text(),spec)
        if profile=='darwin-arm64' and not parsed['target_triple'].startswith(('arm64-apple-','aarch64-apple-')):
            raise SourceError('Compiler target does not match Darwin ARM64 profile')
        if profile=='linux-aarch64' and not parsed['target_triple'].startswith('aarch64-unknown-linux-'):
            raise SourceError('Compiler target does not match Linux AArch64 profile')
        objects=[]
        for src in (f for f in files if f.endswith('.c')):
            dest=build/(profile+'-'+Path(src).stem+'.o')
            run_command([*flags,'-c',src,'-o',str(dest)],commands)
            data=dest.read_bytes()
            objects.append({'source':src,'size':len(data),'sha256':hashlib.sha256(data).hexdigest(),
                            **object_identity(data,profile)})
        profiles[profile]={'probe':parsed,'objects':objects,
                           'ir_sha256':hashlib.sha256(ir.read_bytes()).hexdigest()}
    comparison=compare_layouts(profiles['darwin-arm64']['probe'],profiles['linux-aarch64']['probe'])
    return {'schema_version':1,'status':'PASSED_COMPILE_ONLY' if not comparison['differences'] else 'LAYOUT_DIFFERENCES',
            'timestamp':datetime.now(timezone.utc).isoformat(),'compiler':version,'commands':commands,
            'probe_spec':spec,'generated_source_sha256':hashlib.sha256(generated.read_bytes()).hexdigest(),
            'source_sha256':{f:hashlib.sha256((ROOT/f).read_bytes()).hexdigest() for f in files},
            'profiles':profiles,'comparison':comparison,
            'limits':['Only our original freestanding C types are measured.',
                      'No Darwin SDK, XNU headers, Asahi UAPI or kernel binary was built.',
                      'Object files were not linked, loaded, booted or executed on ARM64.',
                      'Equal selected layouts do not establish syscall, driver, firmware or runtime compatibility.',
                      'Compiler may emit runtime helper references that a later link must satisfy.']}


def main(argv: list[str] | None=None) -> int:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--clang',default=None)
    p.add_argument('--spec',type=Path,default=ROOT/'specs/core-layout-probe.json')
    p.add_argument('--report',type=Path,default=ROOT/'.build/cross-abi.json')
    p.add_argument('--build-dir',type=Path,default=ROOT/'.build/cross-abi')
    a=p.parse_args(argv)
    try:
        cc=a.clang or shutil.which('clang')
        if not cc: raise SourceError('Clang is required; no successful skip')
        report=perform(cc,read_json(a.spec),a.build_dir)
        a.report.parent.mkdir(parents=True,exist_ok=True)
        a.report.write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
        print(json.dumps({'status':report['status'],'report':str(a.report)},indent=2))
        return 0 if report['status']=='PASSED_COMPILE_ONLY' else 1
    except (ValueError,OSError,subprocess.SubprocessError) as exc:
        a.report.parent.mkdir(parents=True,exist_ok=True)
        a.report.write_text(json.dumps({'status':'FAILED_OR_INCOMPLETE','error':str(exc)})+'\n')
        print(str(exc),file=sys.stderr);return 2
if __name__=='__main__': raise SystemExit(main())
