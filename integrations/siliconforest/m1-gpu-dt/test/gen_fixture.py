"""Turns a saved Apple device tree into a C fixture for the host test.

Only the nodes and properties the library reads are copied (see WANTED). The
output holds bytes of a real machine's device tree: it is written under
build/, which is not tracked, and must stay that way.

The ADT format (as m1n1 src/adt.c reads it): a node is u32 property count,
u32 child count, the properties, then the children. A property is a 32-byte
NUL-padded name, a u32 size (top bit is a flag) and the value padded to 4.
"""
import struct
import sys

# path -> property names, or None for every property of the node
WANTED = {
    "/arm-io": ["ranges"],
    "/arm-io/sgx": None,
    "/arm-io/gfx-asc": ["reg"],
    "/chosen": ["firmware-version", "system-firmware-version"],
    # iBoot's memory carve-outs (address, size): the harness checks the UAT regions against them
    "/chosen/carveout-memory-map": None,
    # the display (dispdt.c): register windows to cross-check, the boot framebuffer carve-out
    "/arm-io/dcp": ["reg"],
    "/arm-io/disp0": ["reg"],
    "/arm-io/dart-dcp": ["reg"],
    "/arm-io/dart-disp0": ["reg"],
    "/vram": ["reg"],
    "/": ["compatible"],
}


def parse(buf, off=0):
    nprops, nchildren = struct.unpack_from("<II", buf, off)
    off += 8
    props = {}
    for _ in range(nprops):
        name = buf[off:off + 32].split(b"\0")[0].decode("ascii")
        size = struct.unpack_from("<I", buf, off + 32)[0] & 0x7FFFFFFF
        off += 36
        props[name] = buf[off:off + size]
        off += (size + 3) & ~3
    children = []
    for _ in range(nchildren):
        child, off = parse(buf, off)
        children.append(child)
    return (props, children), off


def find(node, path):
    for comp in [c for c in path.split("/") if c]:
        for child in node[1]:
            if child[0].get("name", b"").rstrip(b"\0").decode("ascii") == comp:
                node = child
                break
        else:
            return None
    return node


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_fixture.py <adt.bin> <out.c>")
    root, _ = parse(open(sys.argv[1], "rb").read())
    out = ["/* Generated by gen_fixture.py from a saved device tree. Do not commit. */",
           '#include "fixture.h"', ""]
    rows = []
    for path, names in WANTED.items():
        node = find(root, path)
        if node is None:
            print("gen_fixture: %s is not in this device tree" % path, file=sys.stderr)
            continue
        for name, value in sorted(node[0].items()):
            if names is not None and name not in names:
                continue
            ident = "v%d" % len(rows)
            body = ", ".join("0x%02x" % b for b in value) or "0"
            out.append("static const unsigned char %s[] = {%s};" % (ident, body))
            rows.append('    {"%s", "%s", %s, %d},' % (path, name, ident, len(value)))
    out += ["", "const struct fixture_prop fixture_props[] = {"] + rows + ["};",
            "const unsigned fixture_nprops = %d;" % len(rows), ""]
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
