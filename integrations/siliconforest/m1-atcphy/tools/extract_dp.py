from pathlib import Path
import argparse,re,hashlib
ap=argparse.ArgumentParser();ap.add_argument('source',type=Path);ap.add_argument('out',type=Path);args=ap.parse_args()
s=args.source.read_text()
def body(name):
 m=re.search(r'static (?:int|void) '+name+r'\([^;]+?\)\n\{',s);assert m,name
 a=m.start();b=s.index('{',m.start());depth=1;i=b+1
 while depth:
  depth+=(s[i]=='{')-(s[i]=='}');i+=1
 return s[a:i]+'\n'
def declaration(start,end):
 a=s.index(start);b=s.index(end,a);return s[a:b]
notice='''// SPDX-License-Identifier: GPL-2.0 OR BSD-2-Clause
/* T8103 DP subset of Omacom linux-aurora 6a08a08e drivers/phy/apple/atc.c.
 * Copyright (C) The Asahi Linux Contributors
 * Author: Sven Peter <sven@kernel.org>
 * Generated by tools/extract_dp.py: specialize T8103, route MMIO/delay to
 * callbacks and require external serialization. No calibration data included.
 */
'''
lines=s[:s.index('enum atcphy_generation')].splitlines(True)
constant_blocks=[]; i=0
while i<len(lines):
 if lines[i].startswith('#define'):
  block=lines[i]
  while lines[i].rstrip().endswith(chr(92)):
   i+=1; block+=lines[i]
  constant_blocks.append(block)
 i+=1
constants=''.join(constant_blocks)

enum=declaration('enum atcphy_dp_link_rate {','/**\n * enum atcphy_pipehandler_state')
config=declaration('struct atcphy_dp_link_rate_configuration {','/* Crossbar and lane configuration */')
a=s.index('static const struct atcphy_dp_link_rate_configuration dp_lr_config[]');b=s.index('\nstatic inline void mask32',a)
tables=s[a:b]
parts=[]
for name in ['atcphy_enable_dp_aux','atcphy_disable_dp_aux','atcphy_dp_configure_lane','atcphy_auspll_apb_command','atcphy_dp_configure','atc_tunnel_stop_t8103','atc_tunnel_pclk_t8103','atc_tunnel_wake_t8103','atc_tunnel_rate_selector','atc_tunnel_start_t8103']:
 t=body(name)
 if name=='atcphy_enable_dp_aux':
  a=t.index('\n\tif (atcphy->hw->has_t8140_dp)');b=t.index('\n\tcore_set32',a);t=t[:a]+t[b:]
 if name=='atcphy_disable_dp_aux':
  a=t.index('\n\tif (atcphy->hw->has_t8140_dp)');b=t.index('\n\t\tset32',a);t=t[:a]+t[b:]
  t=t.replace('\n\t}\n\tcore_clear32','\n\tcore_clear32',1)
