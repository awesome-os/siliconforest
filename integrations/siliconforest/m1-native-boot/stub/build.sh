# Assemble stub/el2_drop.S and write ../native_stub.py (the page as hexadecimal, for the
# launcher on the controller, which has no assembler). `build.sh --check` only compares.
set -euo pipefail
HERE=$(cd "$(dirname "$(readlink -f "$0")")" && pwd)
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
clang --target=aarch64-none-elf -march=armv8.5-a -c "$HERE/el2_drop.S" -o "$T/stub.o"
llvm-objcopy -O binary "$T/stub.o" "$T/stub.bin"
[ "$(stat -c %s "$T/stub.bin")" = 16384 ] || { echo "the stub is not one 16 KiB page" >&2; exit 1; }
{
  echo '# SPDX-License-Identifier: MIT'
  echo '# Generated by stub/build.sh from stub/el2_drop.S; do not edit.'
  echo "STUB_SHA256 = '$(sha256sum "$T/stub.bin" | cut -d' ' -f1)'"
  echo "STUB_HEX = ("
  # the code and vectors are sparse: runs of zero bytes are written as a multiplication
  python3 - "$T/stub.bin" <<'PY'
import sys
data = open(sys.argv[1], 'rb').read()
i = 0
while i < len(data):
    j = i
    while j < len(data) and data[j] == 0:
        j += 1
    if j - i >= 32:
        print("    + '00' * %d" % (j - i)); i = j; continue
    j = i
    while j < len(data) and j - i < 32 and not (data[j:j+32] == bytes(32) and j > i):
        j += 1
    print("    + '%s'" % data[i:j].hex()); i = j
PY
  echo ")"
} | sed '0,/^    + /s//    /' > "$T/native_stub.py"
if [ "${1:-}" = --check ]; then cmp "$T/native_stub.py" "$HERE/../native_stub.py" && echo "native_stub.py matches el2_drop.S"; else cp "$T/native_stub.py" "$HERE/../native_stub.py"; echo "wrote native_stub.py"; fi
