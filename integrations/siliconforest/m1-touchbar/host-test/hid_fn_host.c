/* Host checks of ../spihid/sf_hid_fn.c against descriptors shaped like Apple keyboards'. */
#include "../spihid/sf_hid_fn.h"
#include <stdio.h>

static int failures;
#define CHECK(c) do { if (!(c)) { printf("FAIL line %d: %s\n", __LINE__, #c); failures++; } } while (0)

/* report 1: modifiers, reserved, LEDs (output), six keys, eject (consumer 0xb8), Fn (0xff/0x03), six bits of padding */
static const uint8_t kApple[] = {
	0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x85, 0x01,
	0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
	0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
	0x95, 0x05, 0x75, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x91, 0x02, 0x95, 0x01, 0x75, 0x03, 0x91, 0x01,
	0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x26, 0xff, 0x00, 0x05, 0x07, 0x19, 0x00, 0x2a, 0xff, 0x00, 0x81, 0x00,
	0x05, 0x0c, 0x75, 0x01, 0x95, 0x01, 0x09, 0xb8, 0x15, 0x00, 0x25, 0x01, 0x81, 0x02,
	0x05, 0xff, 0x09, 0x03, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02,
	0x75, 0x06, 0x95, 0x01, 0x81, 0x01,
	0xc0,
	/* a second collection with its own report */
	0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, 0x85, 0x02, 0x05, 0xff, 0x09, 0x03, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02,
	0x75, 0x07, 0x81, 0x01, 0xc0,
};
/* the Fn usage with a two-byte vendor page (0xff00) and first in its byte; no report IDs */
static const uint8_t kVendor16[] = {
	0x05, 0x01, 0x09, 0x06, 0xa1, 0x01,
	0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
	0x06, 0x00, 0xff, 0x09, 0x03, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02, 0x75, 0x07, 0x81, 0x01, 0xc0,
};

/* ten-byte report: the Fn usage as the whole last byte */
static const uint8_t kByte[] = {
	0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x85, 0x01,
	0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
	0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
	0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x26, 0xff, 0x00, 0x05, 0x07, 0x19, 0x00, 0x2a, 0xff, 0x00, 0x81, 0x00,
	0x05, 0xff, 0x09, 0x03, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02,
	0xc0,
};

int
main(void)
{
	unsigned w = 0;
	CHECK(sf_hid_input_field(kByte, sizeof(kByte), 1, 0xff, 0x03, &w) == 72 && w == 8);
	CHECK(sf_hid_input_field(kApple, sizeof(kApple), 1, 0xff, 0x03, &w) == 8 + 8 + 8 + 48 + 1);
	CHECK(sf_hid_input_field(kApple, sizeof(kApple), 2, 0xff, 0x03, &w) == 8);
	CHECK(sf_hid_input_field(kApple, sizeof(kApple), 3, 0xff, 0x03, &w) == -1);
	CHECK(sf_hid_input_field(kApple, sizeof(kApple), 1, 0x0c, 0xb8, NULL) == 72);
	CHECK(sf_hid_input_field(kApple, sizeof(kApple), 1, 0x07, 0xe1, NULL) == 9);        /* left Shift, from a usage range */
	CHECK(sf_hid_input_field(kVendor16, sizeof(kVendor16), 0, 0xff, 0x03, &w) == 8);
	CHECK(sf_hid_input_field(kApple, sizeof(kApple) - 30, 2, 0xff, 0x03, &w) == -1);  /* cut short */
	CHECK(sf_hid_input_field(kApple, 7, 1, 0xff, 0x03, &w) == -1);
	CHECK(sf_hid_input_field(NULL, 0, 1, 0xff, 0x03, &w) == -1);
	printf("HIDFN %s (%d failures)\n", failures ? "FAILED" : "PASS", failures);
	return failures != 0;
}
