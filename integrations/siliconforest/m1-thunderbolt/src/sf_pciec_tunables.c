int sf_pciec_t8103_tune(const struct sf_pciec_io *io,enum sf_pciec_window window)
{
 if(!io || !io->read || !io->write || (unsigned)window>SF_PCIEC_OE)return -EINVAL;
 for(size_t i=0;i<sizeof(entries)/sizeof(entries[0]);++i){
  const struct entry *e=&entries[i];if(e->window!=window)continue;
  uint32_t old;int ret=io->read(io->ctx,window,e->off,&old);if(ret)return ret;
  uint32_t value=(old&~e->clear)|e->set;
  if(value!=old){ret=io->write(io->ctx,window,e->off,value);if(ret)return ret;}
 }
 return 0;
}
